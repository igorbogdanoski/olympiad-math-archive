#!/bin/bash
# ===================================================================
# БРЗО DEPLOYMENT НА app.missmath.net
# Копирај ги командите една по една во SSH терминалот
# ===================================================================

echo "🚀 DEPLOYMENT ЗАПОЧНУВА..."
echo ""

# ===================================================================
# ЧЕКОР 1: Backup на старата апликација (30 секунди)
# ===================================================================
echo "📦 ЧЕКОР 1: Backup на претходната апликација..."
BACKUP_DIR="/root/backup-$(date +%Y%m%d-%H%M%S)"
mkdir -p $BACKUP_DIR
cp -r /var/www/html/* $BACKUP_DIR/ 2>/dev/null || echo "Нема стари фајлови"
cp /etc/nginx/sites-available/default $BACKUP_DIR/nginx-default.conf
echo "✅ Backup завршен: $BACKUP_DIR"
echo ""

# ===================================================================
# ЧЕКОР 2: Clone GitHub репото (1 минута)
# ===================================================================
echo "📥 ЧЕКОР 2: Clone GitHub репото..."
cd /opt/
rm -rf olympiad-math-archive  # Избриши стар clone ако постои
git clone https://github.com/igorbogdanoski/olympiad-math-archive.git
cd olympiad-math-archive
git checkout main
echo "✅ GitHub repo клониран"
echo ""

# ===================================================================
# ЧЕКОР 3: Инсталирај Node.js (ако го нема) (2 минути)
# ===================================================================
echo "🔧 ЧЕКОР 3: Провери Node.js..."
if ! command -v node &> /dev/null; then
    echo "Инсталирам Node.js 20..."
    curl -fsSL https://deb.nodesource.com/setup_20.x | bash -
    apt-get install -y nodejs
else
    echo "✅ Node.js веќе е инсталиран: $(node --version)"
fi
echo ""

# ===================================================================
# ЧЕКОР 4: Build апликацијата (3-5 минути)
# ===================================================================
echo "🔨 ЧЕКОР 4: Build апликацијата..."
cd /opt/olympiad-math-archive/web
npm install
npm run build
echo "✅ Build завршен"
echo ""

# ===================================================================
# ЧЕКОР 5: Копирај built фајлови во nginx root (15 секунди)
# ===================================================================
echo "📂 ЧЕКОР 5: Копирај built фајлови..."
rm -rf /var/www/html/*
cp -r /opt/olympiad-math-archive/web/dist/* /var/www/html/
chown -R www-data:www-data /var/www/html/
echo "✅ Фајлови копирани"
echo ""

# ===================================================================
# ЧЕКОР 6: Провери nginx конфигурација (5 секунди)
# ===================================================================
echo "🔍 ЧЕКОР 6: Провери nginx конфигурација..."
nginx -t
if [ $? -eq 0 ]; then
    echo "✅ Nginx конфигурација е валидна"
else
    echo "❌ Nginx конфигурацијата има грешка!"
    exit 1
fi
echo ""

# ===================================================================
# ЧЕКОР 7: Reload nginx (2 секунди)
# ===================================================================
echo "🔄 ЧЕКОР 7: Reload nginx..."
systemctl reload nginx
echo "✅ Nginx reload-иран"
echo ""

# ===================================================================
# ЧЕКОР 8: Тестирај deployment
# ===================================================================
echo "🧪 ЧЕКОР 8: Тестирај deployment..."
curl -s -I http://localhost/ | head -3
echo ""
curl -s -I https://app.missmath.net/ | head -3
echo ""

# ===================================================================
# ЗАВРШЕНО
# ===================================================================
echo ""
echo "=================================================================="
echo "✅ DEPLOYMENT УСПЕШНО ЗАВРШЕН!"
echo "=================================================================="
echo ""
echo "🌐 Сајтот е достапен на:"
echo "   • https://app.missmath.net/"
echo "   • http://app.missmath.net/"
echo ""
echo "📊 Статистики:"
echo "   • Број на страници: $(find /var/www/html -name '*.html' | wc -l)"
echo "   • Големина: $(du -sh /var/www/html/ | cut -f1)"
echo ""
echo "📁 Backup локација: $BACKUP_DIR"
echo "=================================================================="
